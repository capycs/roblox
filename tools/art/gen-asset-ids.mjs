// Writes src/shared/AssetIds.luau listing every uploaded-image slot (UI icons, particle
// textures, terrain texture maps). IDs already filled in are kept when re-run.
//   cd tools/art && npm run asset-ids
import fs from 'node:fs';
import path from 'node:path';
import { repo } from './serve.mjs';

const out = path.join(repo, 'src/shared/AssetIds.luau');
const old = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
const keep = (section, name) => {
  const m = old.match(new RegExp(`--\\[${section}\\][\\s\\S]*?\\b${name} = "(rbxassetid://\\d+)"`));
  return m ? m[1] : 'rbxassetid://0';
};
const list = (dir) => fs.readdirSync(path.join(repo, dir)).filter((f) => f.endsWith('.png')).map((f) => f.replace(/\.png$/, '')).sort();
const icons = list('assets/ui/icons');
const fx = list('assets/fx/textures');
const textures = JSON.parse(fs.readFileSync(path.join(repo, 'assets/textures/index.json'), 'utf8'));

const lines = [];
lines.push('--!strict');
lines.push('-- Uploaded image IDs. Generated by tools/art/gen-asset-ids.mjs: re-running keeps IDs');
lines.push('-- you already filled in. Upload the PNGs (Asset Manager > Bulk Import), then paste');
lines.push('-- each ID here. Anything left at rbxassetid://0 is treated as missing.');
lines.push('');
lines.push('local AssetIds = {}');
lines.push('');
lines.push('--[Icons] assets/ui/icons/<Name>.png');
lines.push('AssetIds.Icons = {');
for (const n of icons) lines.push(`\t${n} = "${keep('Icons', n)}",`);
lines.push('}');
lines.push('');
lines.push('--[Fx] assets/fx/textures/<Name>.png');
lines.push('AssetIds.Fx = {');
for (const n of fx) lines.push(`\t${n} = "${keep('Fx', n)}",`);
lines.push('}');
lines.push('');
lines.push('--[Textures] assets/textures/<Name>/{color,normal,roughness}.png');
lines.push('AssetIds.Textures = {');
for (const t of textures) {
  lines.push(`\t${t.name} = {`);
  lines.push(`\t\tterrain = "${t.terrain}", studsPerTile = ${t.studsPerTile},`);
  for (const k of ['color', 'normal', 'roughness']) {
    const m = old.match(new RegExp(`${k} = "(rbxassetid://\\d+)", -- ${t.name}_${k}\\b`));
    lines.push(`\t\t${k} = "${m ? m[1] : 'rbxassetid://0'}", -- ${t.name}_${k}`);
  }
  lines.push('\t},');
}
lines.push('}');
lines.push('');
lines.push('--[Portraits] assets/creatures/<Name>/previews/hero.png (Index cards, hatch reveal)');
lines.push('AssetIds.Portraits = {');
for (const c of fs.readdirSync(path.join(repo, 'assets/creatures')).filter((d) => fs.existsSync(path.join(repo, 'assets/creatures', d, 'previews/hero.png'))).sort()) lines.push(`\t${c} = "${keep('Portraits', c)}",`);
lines.push('}');
lines.push('');
lines.push('--[Mutations] assets/creatures/<Name>/mutations/<Mutation>.png (Body texture swaps)');
lines.push('AssetIds.Mutations = {');
for (const c of fs.readdirSync(path.join(repo, 'assets/creatures')).filter((d) => fs.existsSync(path.join(repo, 'assets/creatures', d, 'mutations'))).sort()) {
  lines.push(`\t${c} = {`);
  for (const m of list(`assets/creatures/${c}/mutations`)) {
    const mm = old.match(new RegExp(`${m} = "(rbxassetid://\\d+)", -- ${c}_${m}\\b`));
    lines.push(`\t\t${m} = "${mm ? mm[1] : 'rbxassetid://0'}", -- ${c}_${m}`);
  }
  lines.push('\t},');
}
lines.push('}');
lines.push('');
lines.push('--[Sky] assets/sky/<Name>/<Face>.png');
lines.push('AssetIds.Sky = {');
for (const sky of fs.readdirSync(path.join(repo, 'assets/sky')).sort()) {
  lines.push(`\t${sky} = {`);
  for (const face of ['Bk', 'Dn', 'Ft', 'Lf', 'Rt', 'Up']) {
    const m = old.match(new RegExp(`${face} = "(rbxassetid://\\d+)", -- ${sky}_${face}\\b`));
    lines.push(`\t\t${face} = "${m ? m[1] : 'rbxassetid://0'}", -- ${sky}_${face}`);
  }
  lines.push('\t},');
}
lines.push('}');
lines.push('');
lines.push('-- Returns the ID, or nil when it has not been uploaded yet.');
lines.push('function AssetIds.get(id: string?): string?');
lines.push('\tif id == nil or id == "" or id == "rbxassetid://0" then');
lines.push('\t\treturn nil');
lines.push('\tend');
lines.push('\treturn id');
lines.push('end');
lines.push('');
lines.push('return AssetIds');
fs.writeFileSync(out, lines.join('\n') + '\n');
console.log(`AssetIds: ${icons.length} icons, ${fx.length} fx, ${textures.length} textures`);
